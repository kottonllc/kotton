//! The `surface` domain — the windows apps draw into.
//!
//! ```no_run
//! # async fn example(client: &mut kotton::KottonClient) -> std::io::Result<()> {
//! let mut surface = client.surface();
//! let open = surface.list().await?;
//! # let _ = open;
//! # Ok(())
//! # }
//! ```
//!
//! ## Why this handle binds no user
//!
//! Not because a window belongs to the device — that was an earlier and wrong
//! reading — but because **the caller does not get to choose**. Every window
//! carries a `WindowOwner`, and the daemon fills it in from the authenticated
//! session rather than from the request. [`Surface::list`] returns your windows
//! because it can return no others; there is no argument that would widen it.
//!
//! That is deliberate rather than incidental. `WindowOwner` has a `System`
//! variant for the surfaces that exist before any session — login, lock, the
//! user picker — and a client able to name its own owner could claim it and draw
//! something the shell renders as a login prompt. In a system where a harvested
//! recovery key *is* the account, that is the attack worth the most, so the
//! ability to name an owner is simply absent from the wire.
//!
//! No IPC path registers a `System` window yet. Giving the shell one needs a
//! trusted path of its own — the problem Windows solves with a Secure Desktop
//! and an uninterceptable attention sequence — and that design is not started.

use std::io;

use kotton_wire::ipc::WindowStateDto;

use super::{UserRequest, UserResponse, KottonClient};

impl KottonClient {
    /// Notify the daemon that a WASM app window was opened.
    ///
    /// `instance_id` must be a UUID v4 string generated by the caller.
    pub async fn window_opened(
        &mut self,
        app_id: &str,
        instance_id: &str,
        title: &str,
    ) -> io::Result<()> {
        let req = UserRequest::WindowOpened {
            app_id: app_id.to_string(),
            instance_id: instance_id.to_string(),
            title: title.to_string(),
        };
        match self.client.send(&req).await? {
            UserResponse::WindowAck => Ok(()),
            UserResponse::Error { message } => Err(io::Error::other(message)),
            got => Err(crate::protocol::unexpected(got)),
        }
    }

    /// Notify the daemon that a WASM app window was closed.
    ///
    /// `instance_id` must match the value passed to [`window_opened`].
    pub async fn window_closed(&mut self, instance_id: &str) -> io::Result<()> {
        let req = UserRequest::WindowClosed {
            instance_id: instance_id.to_string(),
        };
        match self.client.send(&req).await? {
            UserResponse::WindowAck => Ok(()),
            UserResponse::Error { message } => Err(io::Error::other(message)),
            got => Err(crate::protocol::unexpected(got)),
        }
    }

    /// Return a snapshot of all currently open WASM app windows from the daemon's
    /// `WindowRegistry`.
    pub async fn window_list(&mut self) -> io::Result<Vec<WindowStateDto>> {
        match self.client.send(&UserRequest::WindowList).await? {
            UserResponse::WindowList { windows } => Ok(windows),
            UserResponse::Error { message } => Err(io::Error::other(message)),
            got => Err(crate::protocol::unexpected(got)),
        }
    }
}

/// The `surface` domain. Device-scoped, so it binds no user.
pub struct Surface<'a> {
    client: &'a mut KottonClient,
}

impl KottonClient {
    /// Enter the `surface` domain.
    pub fn surface(&mut self) -> Surface<'_> {
        Surface { client: self }
    }
}

impl Surface<'_> {
    /// Record that a window opened. See [`KottonClient::window_opened`].
    pub async fn opened(&mut self, app_id: &str, instance_id: &str, title: &str) -> io::Result<()> {
        self.client.window_opened(app_id, instance_id, title).await
    }

    /// Record that a window closed. See [`KottonClient::window_closed`].
    pub async fn closed(&mut self, instance_id: &str) -> io::Result<()> {
        self.client.window_closed(instance_id).await
    }

    /// Every open window. See [`KottonClient::window_list`].
    pub async fn list(&mut self) -> io::Result<Vec<WindowStateDto>> {
        self.client.window_list().await
    }
}
